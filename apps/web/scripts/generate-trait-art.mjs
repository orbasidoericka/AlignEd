// Generates the two trait-art components from the authored SVGs:
//
//   assets/emblems-source/<trait>.svg  ->  src/components/riasec/trait-emblem.tsx
//   assets/mascots-source/<trait>.svg  ->  src/components/riasec/trait-mascot.tsx
//
// Run after editing any source SVG:  npm run generate:trait-art
//
// The art is inlined rather than served from public/ so its colours can be
// tokens: each SVG was authored in the pastel trait palette, and every
// occurrence of the letter's own trait colour becomes `currentColor`, its
// shade becomes var(--trait-shade), and (emblems only) the ink becomes
// var(--trait-foreground). The component sets `color` to the letter's trait
// token, so the art follows the palette in both themes. Everything else
// (skin, hair, props, other traits' accents) stays as authored.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..", "..");
const web = join(here, "..");

// Letter -> [file name, authored trait colour, authored shade].
const TRAITS = {
  R: ["realistic", "#7cafe8", "#3f78bd"],
  I: ["investigative", "#b59be6", "#7a5cc0"],
  A: ["artistic", "#eec96c", "#c0932a"],
  S: ["social", "#9ed691", "#5f9e52"],
  E: ["enterprising", "#f7a284", "#d0694a"],
  C: ["conventional", "#7ad7d1", "#3a9f98"],
};

const JSX_ATTRS = [
  "clip-path",
  "clip-rule",
  "fill-opacity",
  "fill-rule",
  "stroke-dasharray",
  "stroke-linecap",
  "stroke-linejoin",
  "stroke-opacity",
  "stroke-width",
];

function toJsx(markup) {
  let out = markup;
  for (const attr of JSX_ATTRS) {
    const camel = attr.replace(/-(\w)/g, (_m, c) => c.toUpperCase());
    out = out.replaceAll(`${attr}=`, `${camel}=`);
  }
  const leftover = out.match(/\s[a-z]+-[a-z-]+=/);
  if (leftover) throw new Error(`unmapped SVG attribute: ${leftover[0].trim()}`);
  return out;
}

function tokenise(markup, trait, shade, { ink }) {
  let out = markup
    .replace(new RegExp(trait, "gi"), "currentColor")
    .replace(new RegExp(shade, "gi"), "var(--trait-shade)");
  if (ink) out = out.replace(/#0d192f/gi, "var(--trait-foreground)");
  return out.replace(/#ffffff/gi, "#fff");
}

// SVG ids are global to the page. Every mascot clips its neck with
// id="neckclip", so three cards would collide; each id is prefixed with the
// render's useId().
function scopeIds(markup) {
  return markup
    .replace(/ id="([\w-]+)"/g, (_m, id) => ` id={\`\${uid}-${id}\`}`)
    .replace(/"url\(#([\w-]+)\)"/g, (_m, id) => `{\`url(#\${uid}-${id})\`}`);
}

// One element per line, so the generated file diffs line by line.
function lines(markup, indent) {
  return (markup.match(/<[^>]+>/g) ?? []).map((t) => indent + t).join("\n");
}

function readSvg(dir, name) {
  return readFileSync(join(repo, "assets", dir, `${name}.svg`), "utf8")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<\/?svg[^>]*>/g, "")
    .trim();
}

function artMap(name, entries) {
  const body = entries
    .map(([letter, markup]) => {
      const usesId = markup.includes("${uid}");
      return `  ${letter}: (${usesId ? "uid" : ""}) => (\n    <>\n${lines(markup, "      ")}\n    </>\n  ),`;
    })
    .join("\n");
  return `const ${name}: Readonly<\n  Record<RiasecLetter, (uid: string) => React.ReactNode>\n> = {\n${body}\n};`;
}

const HEADER = (source) => `// Copyright (c) 2026 EdTech. All rights reserved.
// GENERATED by scripts/generate-trait-art.mjs from assets/${source}/.
// Do not edit by hand: change the source SVG and run
// \`npm run generate:trait-art\`.
`;

// ---------------------------------------------------------------- emblems
// The emblem is a hex badge plus a glyph. The badge is identical for all six
// once its colours are tokens, so it is written once; the scattered cells
// around it are dropped, because at icon size they read as noise.
const BADGE_START = /points="400\.0,(?:38|56|68)\.0 /;
let badge = null;
const glyphs = [];
for (const [letter, [name, trait, shade]] of Object.entries(TRAITS)) {
  const svg = tokenise(toJsx(readSvg("emblems-source", name)), trait, shade, { ink: true });
  const glyph = (svg.match(/<g transform="translate\(400,290\)">[\s\S]*<\/g>/) ?? [""])[0];
  if (!glyph) throw new Error(`${name}: emblem glyph group not found`);
  const shapes = (svg.replace(glyph, "").match(/<[^>]+>/g) ?? []).filter((t) => BADGE_START.test(t));
  if (shapes.length !== 3) throw new Error(`${name}: expected 3 badge polygons, found ${shapes.length}`);
  const thisBadge = shapes.join("");
  if (badge === null) badge = thisBadge;
  else if (badge !== thisBadge) throw new Error(`${name}: badge differs from the others`);
  const inner = glyph.replace(/^<g transform="translate\(400,290\)">/, "").replace(/<\/g>$/, "");
  glyphs.push([letter, scopeIds(inner)]);
}

const emblemFile = `${HEADER("emblems-source")}
import { useId } from "react";

import { letterArtStyle } from "@/lib/riasec/letter-chip-styles";
import type { RiasecLetter } from "@/lib/riasec/types";
import { cn } from "@/lib/utils";

// The icon for a RIASEC letter: a hex badge, because the RIASEC model is a
// hexagon, carrying a flat glyph for the trait. It stands wherever a letter
// chip used to stand beside a trait's name. Decorative: the name or the code
// beside it always says the same thing in words.
//
// The viewBox crops the authored 800x600 canvas to the badge alone.
const EMBLEM_VIEWBOX = "176 32 448 534";

${artMap("EMBLEM_GLYPHS", glyphs)}

export function TraitEmblem({
  letter,
  className,
}: {
  letter: RiasecLetter;
  /** Sets the size, e.g. "size-8". */
  className?: string;
}) {
  // Only the Social glyph clips against an id, but hooks cannot be called
  // conditionally, so every emblem asks for one.
  const uid = useId();
  return (
    <svg
      viewBox={EMBLEM_VIEWBOX}
      aria-hidden="true"
      focusable="false"
      className={cn("shrink-0", className)}
      style={letterArtStyle(letter)}
    >
${lines(badge, "      ")}
      <g transform="translate(400,290)">{EMBLEM_GLYPHS[letter](uid)}</g>
    </svg>
  );
}
`;

// ---------------------------------------------------------------- mascots
const mascots = [];
for (const [letter, [name, trait, shade]] of Object.entries(TRAITS)) {
  const svg = tokenise(toJsx(readSvg("mascots-source", name)), trait, shade, { ink: false });
  if (!svg.includes("currentColor")) throw new Error(`${name}: own trait colour not found`);
  mascots.push([letter, scopeIds(svg)]);
}

const mascotFile = `${HEADER("mascots-source")}
import { useId } from "react";
import { Crown } from "lucide-react";

import { letterArtStyle, letterWash } from "@/lib/riasec/letter-chip-styles";
import type { RiasecLetter } from "@/lib/riasec/types";
import { cn } from "@/lib/utils";

// The cover of a pathway card: one illustrated character per RIASEC trait,
// standing in its hex, so a student recognises who they are before reading a
// word. The figures run off the bottom of the 800x600 canvas on purpose; the
// band anchors them to its lower edge.
const MASCOT_VIEWBOX = "0 0 800 600";

${artMap("MASCOT_ART", mascots)}

export function TraitMascot({
  letter,
  primary = false,
}: {
  letter: RiasecLetter;
  /** The first letter of the Holland code gets a taller, ringed band. */
  primary?: boolean;
}) {
  // Every figure clips its neck with an id; three cards on one page must not
  // share it.
  const uid = useId();
  return (
    <div
      className={cn(
        // Bleeds to the card edges against BentoGridItem's p-5 / sm:p-6.
        "relative -mx-5 -mt-5 overflow-hidden rounded-t-[1.25rem] sm:-mx-6 sm:-mt-6",
        "flex items-end justify-center",
        // A full-bleed illustration per card is a lot of ink for decoration.
        "print:hidden",
        letterWash(letter),
        primary ? "h-36 sm:h-40" : "h-28 sm:h-32",
      )}
    >
      {primary && (
        // Stated in words, not only in size and color: a border and a taller
        // band tell a screen reader user nothing. The card ground rather than
        // a trait tint, so one badge reads over all six washes in both themes.
        <p
          className="absolute top-3 left-4 z-10 inline-flex items-center gap-1.5 rounded-full
                     bg-card/90 px-2.5 py-1 font-heading text-xs font-bold text-foreground
                     shadow-sm backdrop-blur-sm"
        >
          <Crown className="size-3.5 text-primary-strong" aria-hidden />
          Your top trait
        </p>
      )}
      <svg
        viewBox={MASCOT_VIEWBOX}
        // Decorative: the card's heading already names the trait.
        aria-hidden="true"
        focusable="false"
        className={cn("relative h-full w-auto", primary && "drop-shadow-sm")}
        style={letterArtStyle(letter)}
      >
        {MASCOT_ART[letter](uid)}
      </svg>
    </div>
  );
}
`;

const out = join(web, "src", "components", "riasec");
writeFileSync(join(out, "trait-emblem.tsx"), emblemFile);
writeFileSync(join(out, "trait-mascot.tsx"), mascotFile);
console.log("wrote trait-emblem.tsx and trait-mascot.tsx");
